STRINGS = {"en": _EN, "ja": _JA, "zh": _ZH, "es": _ES, "fr": _FR, "ar": _AR, "hi": _HI}

_MONTHS = {
    "en": "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split(),
    "es": "ene feb mar abr may jun jul ago sept oct nov dic".split(),
    "fr": "janv. févr. mars avr. mai juin juil. août sept. oct. nov. déc.".split(),
    "ar": "يناير فبراير مارس أبريل مايو يونيو يوليو أغسطس سبتمبر أكتوبر نوفمبر ديسمبر".split(),
    "hi": "जन॰ फ़र॰ मार्च अप्रैल मई जून जुल॰ अग॰ सित॰ अक्तू॰ नव॰ दिस॰".split(),
}


def locale_of(value: object) -> str:
    """A known UI locale, else English."""
    return normalize_locale(value) or DEFAULT_LOCALE


def text(locale: str, key: str, **values: object) -> str:
    """The page's own words for `key`, with `{name}` filled in. `n == 1` takes the `_one` form
    where the language has one."""
    table = STRINGS.get(locale, _EN)
    if values.get("n") == 1 and f"{key}_one" in table:
        key = f"{key}_one"
    return table.get(key, _EN[key]).format(**values)


def day(locale: str, value: date, today: date | None = None) -> str:
    """A short date ("Dec 9"), with the year only when it is not the page's year."""
    other_year = today is not None and value.year != today.year
    if locale in ("ja", "zh"):
        short = f"{value.month}月{value.day}日"
        return f"{value.year}年{short}" if other_year else short
    months = _MONTHS.get(locale, _MONTHS["en"])
    if locale == "en":
        short = f"{months[value.month - 1]} {value.day}"
        return f"{short}, {value.year}" if other_year else short
    short = f"{value.day} {months[value.month - 1]}"
    return f"{short} {value.year}" if other_year else short


def month(locale: str, value: date) -> str:
    if locale in ("ja", "zh"):
        return f"{value.month}月"
    return _MONTHS.get(locale, _MONTHS["en"])[value.month - 1]
