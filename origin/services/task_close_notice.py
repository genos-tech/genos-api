"""A closing line in the chat thread a task was made from (MIP-1283, route (b)).

Someone asks for Y in a chat thread, the PM makes a task of it, a developer closes it. The task
card the app posts in the thread says "created" and nothing ever says "closed", so the person
who asked, who may not be on the project and so cannot open the task, never hears. The thread
is the one place that person can read, so the close is told there.

THE LINE
  * Author: nobody (`sender` is null, as for a deleted account) with
    `metadata.systemNotice = "task_closed"`. The closer is NOT impersonated, and no member or
    system user is invented for it.
  * Text: fixed, `Task <display id> is now Closed.` The display id is generated by the system
    (project code and number); the title is NOT in the line: it is user text, this line is read by
    the in-app agent (`fetch_chat_thread`), and the card above it already names the task.
  * No `@mention`, no activity row, no push: it must not ring anybody. It is read when the
    thread is opened or fetched, and by the MCP briefing (`get_my_briefing`: a reply in a
    thread the member started).
  * No `Message.task` and no `metadata.taskId`: those mark the task CARD (the one-task-per-
    thread guard and the PM "one bubble per task" selector read the card, not this line).
  * Once per close: the idempotency key is the status row that closed the task
    (`correlation_id = task-closed:<task>:<activity>`), so a retry collapses, while a task
    that is reopened and closed again says it again: that is a second piece of news.

FLAG
  `SEARCH_ENGINE["AGENT_CLOSING_LINE_IN_ORIGIN_THREAD"]` (default off, read at every close):
  off posts nothing. The line is chat content `fetch_chat_thread` hands the in-app model, so
  it is measured before it ships (the `t1283` arm of the grouped eval).

WHEN
  Posted from the `TaskMaster` post_save handler, in the same transaction as the status row, so
  a rolled-back close posts nothing. A failure here is logged and never fails the task write.
  A bulk `QuerySet.update` skips signals, as it skips every other audit row.

WHERE
  Only a thread the task really came from: `thread_id` names a live top-level message of a
  DM/GM/MDM channel in the task's team, and `chat_id` is that very channel (legacy rows point
  at another channel or hold a number: they get nothing).

It is written through the chat funnel (`_allocate_seq_and_create_message`: per-channel seq under
the channel lock, thread root and reply count, the idempotency key), not by a raw insert.
"""

from __future__ import annotations

import logging
import uuid

from django.conf import settings

from origin.models.chat.unified_models import Channel, ChannelKind, Message
from origin.models.task.task_models import TaskMaster

logger = logging.getLogger("origin.task_close_notice")

NOTICE_KIND = "task_closed"
_KINDS = (ChannelKind.DM, ChannelKind.GM, ChannelKind.MDM)


def notice_text(display_id: str) -> str:
    return f"Task {display_id} is now Closed."


def _thread_root(task: TaskMaster) -> Message | None:
    """The live top-level message the task was made from, or None."""
    try:
        root_id = uuid.UUID(str(task.thread_id))
    except ValueError:
        return None  # empty, or a legacy numeric id
    root = (
        Message.objects.select_related("channel")
        .filter(id=root_id, is_thread_reply=False, deleted_at__isnull=True)
        .first()
    )
    if root is None:
        return None
    channel: Channel = root.channel
    if (
        channel.is_deleted
        or channel.kind not in _KINDS
        or str(channel.team_id) != str(task.team_id)
        or str(channel.id) != str(task.chat_id)
    ):
        return None
    return root


def post_close_notice(task: TaskMaster, closing_activity_id: int) -> Message | None:
    """Tell the origin thread that `task` closed. Returns the line, or None when the task has no
    thread to tell. Never raises."""
    try:
        # Model-visible (the in-app agent reads threads), so dark-shipped: flag off posts
        # nothing, and the thread is what it was before this existed.
        if not settings.SEARCH_ENGINE.get("AGENT_CLOSING_LINE_IN_ORIGIN_THREAD", False):
            return None
        if task.is_deleted or task.is_init_task or not task.thread_id:
            return None
        root = _thread_root(task)
        if root is None:
            return None
        from origin.views.chat.message_views import _allocate_seq_and_create_message  # noqa: PLC0415

        text = notice_text(task.display_id)
        # The funnel runs in its own `atomic` (a savepoint inside the close's transaction), so
        # a failure here rolls back the line alone and leaves the close standing.
        return _allocate_seq_and_create_message(
            channel=root.channel,
            sender=None,
            body=[{"type": "paragraph", "content": [{"type": "text", "text": text}]}],
            body_text=text,
            parent_id=root.id,
            metadata={"systemNotice": NOTICE_KIND, "closedTaskDisplayId": task.display_id},
            correlation_id=f"task-closed:{task.task_id}:{closing_activity_id}",
        )
    except Exception:  # noqa: BLE001 - the notice is an observer of the close, never its failure
        logger.warning("close notice failed for task=%s", getattr(task, "pk", None), exc_info=True)
        return None
